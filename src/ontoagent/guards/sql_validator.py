"""SQL query validator and AST rewriter for OntoAgent.

Purpose:
    First of two read-only defenses for the SQL specialist (Threat T4).
    Validates AST using sqlglot (Postgres dialect).
    Enforces single SELECT statements, function blocklists, table and column allowlists,
    role-based row policies, star expansion, and LIMIT injection/clamping.
"""

from dataclasses import dataclass, field
import re
from typing import List, Optional, Set
import sqlglot
from sqlglot import exp
from sqlglot.errors import SqlglotError

from ontoagent.guards.rbac import get_role_policy
from ontoagent.ontology.models import Ontology


@dataclass
class ValidationResult:
    """Outcome of SQL validation and rewriting."""
    ok: bool
    code: str
    reasons: List[str] = field(default_factory=list)
    rewritten_sql: Optional[str] = None


FORBIDDEN_FUNC_PREFIXES = (
    "pg_", "lo_", "dblink", "set_config", "current_setting",
    "txid_", "query_to_xml", "xpath"
)


def validate_sql(sql: str, role: str, onto: Ontology) -> ValidationResult:
    """Validate and rewrite an LLM-generated SQL query before execution.

    Args:
        sql: Raw SQL text generated by the model.
        role: Persona role ('analyst' or 'ops_manager').
        onto: Loaded domain ontology.

    Returns:
        ValidationResult with rewritten_sql when valid. Codes starting with
        SEC_ are non-repairable security violations.
    """
    if not sql or not sql.strip():
        return ValidationResult(ok=False, code="SYNTAX_ERROR", reasons=["Empty SQL query"])

    # Clean markdown code blocks if wrapped
    cleaned = re.sub(r"^```(?:sql)?\s*", "", sql.strip(), flags=re.IGNORECASE)
    cleaned = re.sub(r"\s*```$", "", cleaned.strip())

    # Check for multiple statements separated by semicolon before stripping comments
    # Remove strings first to avoid semicolons inside literals
    no_strings = re.sub(r"'(?:''|[^'])*'", "", cleaned)
    # Strip comments
    no_comments = re.sub(r"--[^\n]*", "", no_strings)
    no_comments = re.sub(r"/\*[\s\S]*?\*/", "", no_comments)
    statements = [s.strip() for s in no_comments.split(";") if s.strip()]
    if len(statements) > 1:
        return ValidationResult(
            ok=False,
            code="SEC_MULTI_STATEMENT",
            reasons=["Multiple SQL statements detected"]
        )

    # 1. Parse statement with sqlglot
    try:
        parsed_statements = sqlglot.parse(cleaned, read="postgres")
    except SqlglotError as e:
        return ValidationResult(ok=False, code="SYNTAX_ERROR", reasons=[f"SQL parse error: {str(e)}"])

    if not parsed_statements or parsed_statements[0] is None:
        return ValidationResult(ok=False, code="SYNTAX_ERROR", reasons=["Could not parse statement"])
    if len(parsed_statements) > 1:
        return ValidationResult(
            ok=False,
            code="SEC_MULTI_STATEMENT",
            reasons=["Multiple parsed statements detected"]
        )

    ast = parsed_statements[0]

    # 2. Statement type check: root must be Select / Union / Expression that resolves to Select
    allowed_types = (exp.Select, exp.Union)
    if not isinstance(ast, allowed_types):
        return ValidationResult(
            ok=False,
            code="SEC_NOT_SELECT",
            reasons=[f"Statement type '{ast.key}' is forbidden; only SELECT queries are permitted"]
        )

    # 3. Forbidden constructs: SELECT ... INTO, FOR UPDATE, FOR SHARE
    for into_expr in ast.find_all(exp.Into):
        return ValidationResult(
            ok=False,
            code="SEC_FORBIDDEN_CLAUSE",
            reasons=["SELECT INTO clause is forbidden"]
        )
    for lock in ast.find_all(exp.Lock):
        return ValidationResult(
            ok=False,
            code="SEC_FORBIDDEN_CLAUSE",
            reasons=["Row locking clauses (FOR UPDATE/SHARE) are forbidden"]
        )

    # 4. Function blocklist
    for func in ast.find_all(exp.Anonymous, exp.Func, exp.GenerateSeries):
        name = getattr(func, "name", "") or getattr(func, "key", "")
        name = name.lower()
        if any(name.startswith(prefix) for prefix in FORBIDDEN_FUNC_PREFIXES):
            return ValidationResult(
                ok=False,
                code="SEC_FORBIDDEN_FUNCTION",
                reasons=[f"Function '{name}' is forbidden"]
            )
        # Check generate_series bound
        if "generate_series" in name or isinstance(func, exp.GenerateSeries):
            for lit in func.find_all(exp.Literal):
                if lit.is_number:
                    try:
                        if int(lit.this) > 100000:
                            return ValidationResult(
                                ok=False,
                                code="SEC_FORBIDDEN_FUNCTION",
                                reasons=["generate_series range exceeds maximum allowed limit (100000)"]
                            )
                    except ValueError:
                        pass

    # RBAC policy for role
    policy = get_role_policy(role)
    allowed_tables = set(policy.allowed_tables)
    denied_columns = set(policy.denied_columns)

    # 5. Table allowlist (track CTEs)
    cte_names: Set[str] = {
        cte.alias.lower() for cte in ast.find_all(exp.CTE) if cte.alias
    }

    # Build known table and column maps from ontology
    ontology_table_map = {}
    for entity in onto.entities.values():
        if entity.sql_table:
            ontology_table_map[entity.sql_table.lower()] = set(entity.properties.keys())

    tables_in_query = []
    table_aliases = {}
    for table_expr in ast.find_all(exp.Table):
        tbl_name = table_expr.name.lower()
        if table_expr.alias:
            table_aliases[table_expr.alias.lower()] = tbl_name
        # If it's a CTE reference, it's allowed internally
        if tbl_name in cte_names:
            continue

        db_schema = table_expr.db.lower() if table_expr.db else ""
        qualified = f"{db_schema}.{tbl_name}" if db_schema else tbl_name

        # If not schema-qualified, check if it matches an allowed analytics table
        if not db_schema:
            if f"analytics.{tbl_name}" in allowed_tables:
                # Rewrite table to be schema-qualified
                table_expr.set("db", exp.to_identifier("analytics"))
                qualified = f"analytics.{tbl_name}"
            else:
                return ValidationResult(
                    ok=False,
                    code="SEC_TABLE_DENIED",
                    reasons=[f"Table '{tbl_name}' must be schema-qualified (e.g. analytics.{tbl_name})"]
                )

        if qualified not in allowed_tables:
            return ValidationResult(
                ok=False,
                code="SEC_TABLE_DENIED",
                reasons=[f"Access to table '{qualified}' is denied for role '{role}'"]
            )
        tables_in_query.append(qualified)

    # 6. Column check & Star expansion
    # Expand SELECT * if present
    select_exprs = ast.expressions
    new_select_exprs = []
    has_star = False
    for expr_item in select_exprs:
        if isinstance(expr_item, exp.Star):
            has_star = True
            # Expand to allowed columns of the primary table
            if tables_in_query:
                primary_table = tables_in_query[0]
                cols = ontology_table_map.get(primary_table, set())
                for col in sorted(cols):
                    full_col = f"{primary_table}.{col}"
                    if full_col not in denied_columns:
                        new_select_exprs.append(exp.column(col))
        else:
            new_select_exprs.append(expr_item)

    if has_star:
        ast.set("expressions", new_select_exprs)

    # Check for denied columns (resolving aliases)
    for col_expr in ast.find_all(exp.Column):
        col_name = col_expr.name.lower()
        col_table = col_expr.table.lower() if col_expr.table else ""
        resolved_table = table_aliases.get(col_table, col_table)
        for denied in denied_columns:
            parts = denied.lower().split(".")
            d_col = parts[-1]
            d_table = parts[-2] if len(parts) > 1 else ""
            if col_name == d_col:
                if not resolved_table or resolved_table == d_table or resolved_table == d_table.split(".")[-1]:
                    return ValidationResult(
                        ok=False,
                        code="SEC_COLUMN_DENIED",
                        reasons=[f"Access to column '{denied}' is denied for role '{role}'"]
                    )

    # 7. Row policy check for aggregate_only
    if policy.row_level == "aggregate_only":
        has_agg = bool(list(ast.find_all(exp.AggFunc)))
        has_group = bool(ast.args.get("group"))
        limit_expr = ast.args.get("limit")
        limit_val = None
        if limit_expr and isinstance(limit_expr.expression, exp.Literal):
            try:
                limit_val = int(limit_expr.expression.this)
            except ValueError:
                pass

        if not (has_agg or has_group or (limit_val is not None and limit_val <= 20)):
            return ValidationResult(
                ok=False,
                code="ROW_POLICY_VIOLATION",
                reasons=["Role 'analyst' requires aggregate queries, GROUP BY, or LIMIT <= 20"]
            )

    # 8. Cost guard: reject > 6 joins
    joins = list(ast.find_all(exp.Join))
    if len(joins) > 6:
        return ValidationResult(
            ok=False,
            code="COST_GUARD",
            reasons=[f"Query has {len(joins)} joins (maximum allowed is 6)"]
        )

    # 9. LIMIT injection and clamping (clamp to 1000)
    limit_clause = ast.args.get("limit")
    if not limit_clause:
        ast.set("limit", exp.Limit(expression=exp.Literal.number(1000)))
    else:
        if isinstance(limit_clause.expression, exp.Literal) and limit_clause.expression.is_number:
            try:
                val = int(limit_clause.expression.this)
                if val > 1000:
                    limit_clause.set("expression", exp.Literal.number(1000))
            except ValueError:
                limit_clause.set("expression", exp.Literal.number(1000))

    rewritten_sql = ast.sql(dialect="postgres")
    return ValidationResult(ok=True, code="OK", rewritten_sql=rewritten_sql)
